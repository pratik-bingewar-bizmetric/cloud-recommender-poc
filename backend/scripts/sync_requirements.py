"""Regenerate the pip requirement files from ``uv.lock`` (the single source of truth).

``pyproject.toml`` holds the human-edited dependency *ranges*; ``uv.lock`` holds the exact,
hash-verified resolution. This script derives, deterministically and without ``pip freeze``:

* ``requirements.lock.txt``      - exact pins for the whole runtime closure (constraints file)
* ``requirements-dev.lock.txt``  - runtime + dev tooling closure (CI / local development)
* ``requirements.txt``           - the direct runtime dependencies pinned to the locked versions,
                                   constrained by ``requirements.lock.txt`` (what App Service /
                                   Oryx installs)

Usage (run from ``backend/``; needs ``uv`` on PATH)::

    python scripts/sync_requirements.py           # rewrite the files
    python scripts/sync_requirements.py --check   # exit 1 when any file is out of date (CI)
"""

import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
HEADER = (
    "# GENERATED by scripts/sync_requirements.py from uv.lock - do not edit by hand.\n"
    "# Change dependencies in pyproject.toml, run `uv lock`, then re-run the script.\n"
)


def _export(*flags: str) -> str:
    cmd = ["uv", "export", "--frozen", "--no-hashes", "--no-emit-project", "--quiet", *flags]
    out = subprocess.run(cmd, cwd=BACKEND, check=True, capture_output=True, text=True).stdout
    # Drop uv's own banner (it embeds the command line and version) and keep the pins only.
    lines = [ln for ln in out.splitlines() if ln.strip() and not ln.startswith("#")]
    return "\n".join(lines) + "\n"


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _direct_requirements() -> str:
    project = tomllib.loads((BACKEND / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    lock = tomllib.loads((BACKEND / "uv.lock").read_text(encoding="utf-8"))
    versions = {_canonical(p["name"]): p["version"] for p in lock["package"]}
    lines = []
    for spec in project["dependencies"]:
        match = re.match(r"^([A-Za-z0-9_.-]+)(\[[^\]]+\])?", spec)
        if match is None:
            raise SystemExit(f"Cannot parse dependency: {spec}")
        name, extras = match.group(1), match.group(2) or ""
        lines.append(f"{name}{extras}=={versions[_canonical(name)]}")
    return (
        HEADER
        + "# Direct runtime dependencies, pinned to the locked (tested) versions.\n"
        + "# Transitive dependencies are pinned by the constraints file below.\n"
        + "-c requirements.lock.txt\n\n"
        + "\n".join(lines)
        + "\n"
    )


def build() -> dict[str, str]:
    return {
        "requirements.txt": _direct_requirements(),
        "requirements.lock.txt": HEADER + _export("--no-dev"),
        "requirements-dev.lock.txt": HEADER + _export("--group", "dev"),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any file would change")
    args = parser.parse_args()
    stale = []
    for name, content in build().items():
        path = BACKEND / name
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""
        if current != content:
            stale.append(name)
            if not args.check:
                path.write_text(content, encoding="utf-8", newline="\n")
                print(f"wrote {name}")
    if args.check and stale:
        print("Out of date (run `python scripts/sync_requirements.py`): " + ", ".join(stale))
        return 1
    if not stale:
        print("requirement files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
